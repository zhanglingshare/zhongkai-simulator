/* V3.5 strictly past-only reconstructed baseline diagnostics, never Sim calibration. */
const assert=require("node:assert/strict");
const fs=require("node:fs");
const path=require("node:path");
const B=require("../benchmark-core.js");
const original=JSON.parse(fs.readFileSync(path.resolve(__dirname,"../observations/annual-2019-2025.json"),"utf8"));
const gdp=B.evaluate(original,"gdp_real_yoy");
assert.equal(gdp.eligible,true,gdp.reason);
assert.deepEqual(gdp.folds.map(x=>x.year),[2023,2024,2025]);
assert.equal(gdp.folds[0].actual,10.1);
assert.equal(gdp.folds[0].naive,6.4);
assert.equal(gdp.folds[0].training_end,2022);
assert.ok(Math.abs(gdp.folds[0].mean-(.1+17.9+6.4)/3)<1e-10);
assert.equal(gdp.folds[1].naive,10.1);
assert.equal(gdp.folds[2].naive,4.0);
assert.equal(gdp.modelCalibrated,false);
assert.equal(gdp.certified,false);
assert.equal(gdp.notIndependent,true);
assert.ok(gdp.caveat.includes("事后"));
assert.equal(gdp.scores.n,3);
const invest=B.evaluate(original,"industry_invest_growth");
assert.equal(invest.eligible,true);
assert.deepEqual(invest.folds.map(x=>x.year),[2022,2023,2024,2025]);
const industrial=B.evaluate(original,"industry_growth");
assert.equal(industrial.eligible,true);
assert.deepEqual(industrial.folds.map(x=>x.year),[2023,2024,2025]);
assert.equal(B.evaluate(original,"gdp_current").eligible,false);
assert.equal(B.evaluate(original,"retail_current").eligible,false);
const incomplete=structuredClone(original);
incomplete.observations=incomplete.observations.filter(x=>!(x.metric==="gdp_real_yoy"&&x.year===2022));
const missing=B.evaluate(incomplete,"gdp_real_yoy");
assert.equal(missing.eligible,false);
assert.ok(missing.reason.includes("缺失年份"));
const future=structuredClone(original);
future.observations.find(x=>x.metric==="gdp_real_yoy"&&x.year===2025).value=-99;
const futureTest=B.evaluate(future,"gdp_real_yoy");
assert.deepEqual(futureTest.folds.slice(0,2),gdp.folds.slice(0,2),"2025 target must not change any previous folds");
assert.equal(futureTest.folds[2].naive,gdp.folds[2].naive,"2025 actual must not enter its own forecast input");
const duplicate=structuredClone(original);
duplicate.observations.push({...duplicate.observations.find(x=>x.metric==="gdp_real_yoy"&&x.year===2024)});
assert.equal(B.evaluate(duplicate,"gdp_real_yoy").eligible,false);
const noSource=structuredClone(original);
noSource.observations.find(x=>x.metric==="gdp_real_yoy"&&x.year===2022).source_ids=[];
assert.equal(B.evaluate(noSource,"gdp_real_yoy").eligible,false);
const short=structuredClone(original);
short.observations=short.observations.filter(x=>x.metric!=="gdp_real_yoy"||x.year>=2023);
assert.equal(B.evaluate(short,"gdp_real_yoy").eligible,false);
console.log("PASS V3.5 reconstructed baselines: folds use prior years only, no status as Sim calibration, gaps/duplicates/source failures blocked");
