/* V3.13: deterministic hypothetical inflow runs *existing* Sim and preserves truth boundaries. */
const assert=require("node:assert/strict"),fs=require("node:fs"),path=require("node:path"),vm=require("node:vm");
const root=path.resolve(__dirname,"../.."),context=vm.createContext({window:{}});
for(const script of ["inflow-core.js","inflow.js"]){
 new vm.Script(fs.readFileSync(path.join(root,"v3",script),"utf8"),{filename:script});
}
vm.runInContext(fs.readFileSync(path.join(root,"v3/portal-kernel.js"),"utf8"),context,{filename:"portal-kernel.js"});
const Sim=context.window.ZKSim,Core=require("../inflow-core.js");
assert.equal(typeof Sim,"function");
const initial=new Sim(23,{n_agents:24,ticks:20});
const targets=initial.agents.filter(a=>a.w>=3).slice(0,2).map(a=>a.name);
assert.equal(targets.length,2,"Test needs two guaranteed-appearance model core nodes");
const raw={name:"待核验的新增配套企业 A",type:"supplier",weight:1,seed:23,targets,
  evidence:"unverified",source:"",notes:"本例没有签约证据"};
const verify=Core.validate(Sim,raw);
assert.ok(verify.ok,JSON.stringify(verify.errors));
assert.ok(verify.warnings.some(x=>x.includes("未经独立核验")));
const out=Core.run(Sim,raw,24);
assert.equal(out.ok,true);
assert.equal(out.protocol,"zk-inflow-research-1");
assert.equal(out.baseCount,24);
assert.equal(out.addedCount,25);
assert.equal(out.edges.filter(x=>x.layer==="hypothesis").length,2);
assert.equal(out.edges.length,initial.edges.length+2,"Adding hypothetical links cannot silently rewire baseline");
assert.equal(out.series.length,21,"Must preserve T0–T20 snapshots");
assert.equal(out.actorsByTick.length,21);
assert.ok(out.actorsByTick.every(x=>x.length===25));
assert.equal(out.series[0].metrics.existingAlive.delta,0);
assert.ok(out.agents0.some(a=>a.name===raw.name));
assert.equal(out.includedSeeds,24);
assert.equal(out.excludedSeeds,0);
assert.ok(out.samples.every(x=>!x.excluded));
assert.ok(out.samples.every(x=>Object.values(x.deltas).every(Number.isFinite)));
assert.equal(out.researchStatus,"exploratory-not-calibrated");
assert.ok(out.limitations.some(x=>x.includes("因果效应")));
const rerun=Core.run(Sim,raw,24);
assert.deepEqual(out.series,rerun.series,"Exact same seed/scenario must reproduce A/B");
assert.deepEqual(out.samples,rerun.samples,"Sample distributions must be deterministic");
assert.ok(out.distribution.abundance.p10<=out.distribution.abundance.p50);
assert.ok(out.distribution.abundance.p50<=out.distribution.abundance.p90);
const one=new Sim(23,{n_agents:24,ticks:20}).agents[0].name;
const badName=Core.validate(Sim,{...raw,name:one});
assert.equal(badName.ok,false,"Cannot duplicate existing model actor");
assert.equal(Core.validate(Sim,{...raw,weight:3}).ok,false,"Core actor exemption cannot be assumed");
assert.equal(Core.validate(Sim,{...raw,targets:["不存在的主体"]}).ok,false);
assert.equal(Core.validate(Sim,{...raw,source:"http://unsafe.example"}).ok,false);
assert.equal(Core.validate(Sim,{...raw,targets:[raw.name]}).ok,false);
assert.equal(Core.validate(Sim,{...raw,name:"<script>"}).ok,false);
assert.equal(Core.run(Sim,{...raw,targets:[]}).ok,false,"No invented relationships");
const noContract={...raw,evidence:"public_document",source:"https://example.org/unverified"};
const warn=Core.validate(Sim,noContract);
assert.ok(warn.warnings.some(x=>x.includes("不等于来源已认证")));
assert.ok(Core.questions(raw).some(x=>x.includes("合同")));
const markup=fs.readFileSync(path.join(root,"v3/inflow.html"),"utf8");
assert.match(markup,/portal-kernel\.js/);
assert.match(markup,/inflow-core\.js/);
assert.match(markup,/inflow\.js/);
assert.match(markup,/不是 GDP 预测/);
assert.doesNotMatch(markup,/https:\/\/(cdn|unpkg|jsdelivr)/);
console.log("PASS V3.13 actual Sim inflow, no fabricated relations, reproducible seeds, validation gates and research caveats");
